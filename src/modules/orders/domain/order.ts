/** Required acknowledgement and every label are fictional (PRD J5): there is no balance and no real address. */
export const DESTINATION_PRESETS = ["dream_apartment", "dream_workspace"] as const;
export type DestinationPreset = (typeof DESTINATION_PRESETS)[number];
export const PAYMENT_LABELS = ["dream_credits"] as const;
export type PaymentLabel = (typeof PAYMENT_LABELS)[number];

export const ORDER_CODE_PATTERN = /^DC-V-[0-9A-HJKMNP-TV-Z]{10}$/;

const CROCKFORD = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";

/**
 * Display code `DC-V-` plus 10 base-32 characters (ARCHITECTURE §4). The random bytes come from the injected
 * `IdGenerator`; a unique index in storage decides collisions. The `V` marks it as virtual: it cannot be
 * mistaken for a real order number.
 */
export function formatOrderCode(randomBytes: Uint8Array): string {
  if (randomBytes.length < 10) throw new RangeError("Order code needs 10 random bytes");
  let suffix = "";
  for (let i = 0; i < 10; i++) suffix += CROCKFORD[randomBytes[i]! & 31];
  return `DC-V-${suffix}`;
}

export const imageRefSchema = z.strictObject({
  mediaId: z.string().min(1).max(128),
  file: z.string().min(1).max(512),
  rightsStatus: z.enum(["CLEARED", "PENDING", "NOT_CLEARED"]),
  attributionText: z.string().max(500).optional(),
});
export type ImageRef = z.infer<typeof imageRefSchema>;

const attributesSchema = z.record(
  z.string().max(40),
  z.union([z.string().max(80), z.number().finite()]),
);

/** Everything an order needs to render forever (docs/CATALOG_SCHEMA.md "Order snapshot"). */
export const orderItemSnapshotSchema = z.strictObject({
  productId: z.string().min(1).max(128),
  variantId: z.string().min(1).max(128),
  offerId: z.string().min(1).max(128),
  brand: z.string().min(1).max(120),
  titleVi: z.string().min(1).max(300),
  attributes: attributesSchema,
  quantity: z.number().int().min(1).max(99),
  merchantName: z.string().min(1).max(120),
  sourceUrl: z.string().min(1).max(2048),
  price: priceObservationSchema,
  priceStateAtPlacement: z.enum(["OBSERVED", "STALE", "USER_ENTERED"]),
  /** True when the "price may have changed" warning was shown at placement. */
  freshnessWarningShown: z.boolean(),
  sourcePersistencePolicy: z.enum(PERSISTENCE_POLICIES),
  imageRef: imageRefSchema.nullable(),
});
export type OrderItemSnapshot = z.infer<typeof orderItemSnapshotSchema>;

export const virtualOrderSchema = z.strictObject({
  id: z.string().min(8).max(64),
  code: z.string().regex(ORDER_CODE_PATTERN),
  /** Always true: every order is virtual and says so (ADR-001). */
  virtual: z.literal(true),
  idempotencyKey: z.string().min(8).max(128),
  cartRevision: z.number().int().min(0).safe(),
  createdAtMs: z.number().int().safe().min(0),
  catalogVersion: z.string().min(1).max(128),
  items: z.array(orderItemSnapshotSchema).min(1).max(200),
  total: z.strictObject({
    amountMinor: z.number().int().safe().min(1),
    currency: z.literal(CHECKOUT_CURRENCY),
  }),
  destination: z.enum(DESTINATION_PRESETS),
  payment: z.enum(PAYMENT_LABELS),
  acknowledgedSimulation: z.literal(true),
  simulation: simulationRecordSchema,
});
export type VirtualOrder = z.infer<typeof virtualOrderSchema>;

/** Catalog data for one cart line, resolved by the application layer at placement time. */
export interface ResolvedLine {
  readonly productId: string;
  readonly brand: string;
  readonly titleVi: string;
  readonly attributes: Readonly<Record<string, string | number>>;
  readonly merchantName: string;
  readonly sourceUrl: string;
  readonly price: PriceObservation | null;
  readonly sourcePolicy: PersistencePolicy;
  readonly imageRef: ImageRef | null;
}

export interface PlaceOrderInput {
  /** The key the caller is placing under; it must be the cart's current `checkoutKey`. */
  readonly idempotencyKey: string;
  readonly cart: Cart;
  readonly resolveLine: (variantId: string, offerId: string) => ResolvedLine | null;
  readonly nowMs: number;
  readonly freshness?: FreshnessConfig;
  readonly scenario: ScenarioKey;
  readonly destination: DestinationPreset;
  readonly payment: PaymentLabel;
  /** The required "no real transaction" acknowledgement. */
  readonly acknowledged: boolean;
  readonly catalogVersion: string;
  /** Pre-generated by the caller (the domain has no randomness). */
  readonly orderId: string;
  readonly code: string;
}

export type PlaceOrderError =
  | { readonly error: "not_acknowledged" }
  | { readonly error: "stale_cart" }
  | { readonly error: "invalid_scenario" }
  | { readonly error: "cart_not_checkoutable"; readonly status: Exclude<CheckoutStatus, "ok"> }
  | { readonly error: "line_unresolved"; readonly keys: readonly string[] }
  | { readonly error: "line_ineligible"; readonly key: string; readonly reason: IneligibleReason }
  /** The catalog price differs from what the user added: the user must see it again, nothing is updated silently. */
  | { readonly error: "price_changed"; readonly keys: readonly string[] };

export type PlaceOrderResult =
  | { readonly ok: true; readonly status: "created" | "existing"; readonly order: VirtualOrder }
  | ({ readonly ok: false } & PlaceOrderError);

/**
 * Idempotent placement decision. If an order already exists for this key it is returned unchanged (a
 * double click, a refresh, or a second tab all land here). Otherwise the cart is re-validated against the
 * catalog at `nowMs` and an immutable snapshot is built. Persistence runs the same logic inside one
 * transaction (Phase 4); this function only decides.
 */
export function placeOrder(
  input: PlaceOrderInput,
  existing: VirtualOrder | null,
): PlaceOrderResult {
  if (existing && existing.idempotencyKey === input.idempotencyKey) {
    return { ok: true, status: "existing", order: existing };
  }
  if (!input.acknowledged) return { ok: false, error: "not_acknowledged" };
  if (input.cart.checkoutKey !== input.idempotencyKey) return { ok: false, error: "stale_cart" };
  if (!SCENARIO_KEYS.includes(input.scenario)) return { ok: false, error: "invalid_scenario" };
  const status = checkoutStatus(input.cart);
  if (status !== "ok") return { ok: false, error: "cart_not_checkoutable", status };

  const freshness = input.freshness ?? DEFAULT_FRESHNESS;
  const unresolved: string[] = [];
  const changed: string[] = [];
  const items: OrderItemSnapshot[] = [];

  for (const line of input.cart.lines) {
    const key = lineKey(line);
    const resolved = input.resolveLine(line.variantId, line.offerId);
    if (!resolved) {
      unresolved.push(key);
      continue;
    }
    if (resolved.price === null)
      return { ok: false, error: "line_ineligible", key, reason: "no_price" };
    const evaluation = evaluateOffer(
      { sourcePolicy: resolved.sourcePolicy, price: resolved.price },
      input.nowMs,
      freshness,
    );
    if (!evaluation.addable) {
      return { ok: false, error: "line_ineligible", key, reason: evaluation.reason! };
    }
    if (
      resolved.price.amountMinor !== line.unitPrice.amountMinor ||
      resolved.price.currency !== line.unitPrice.currency
    ) {
      changed.push(key);
      continue;
    }
    items.push({
      productId: resolved.productId,
      variantId: line.variantId,
      offerId: line.offerId,
      brand: resolved.brand,
      titleVi: resolved.titleVi,
      attributes: { ...resolved.attributes },
      quantity: line.quantity,
      merchantName: resolved.merchantName,
      sourceUrl: resolved.sourceUrl,
      price: { ...resolved.price },
      priceStateAtPlacement: evaluation.state as "OBSERVED" | "STALE" | "USER_ENTERED",
      freshnessWarningShown: evaluation.state === "STALE",
      sourcePersistencePolicy: resolved.sourcePolicy,
      imageRef: resolved.imageRef ? { ...resolved.imageRef } : null,
    });
  }
  if (unresolved.length > 0) return { ok: false, error: "line_unresolved", keys: unresolved };
  if (changed.length > 0) return { ok: false, error: "price_changed", keys: changed };

  const order: VirtualOrder = {
    id: input.orderId,
    code: input.code,
    virtual: true,
    idempotencyKey: input.idempotencyKey,
    cartRevision: input.cart.revision,
    createdAtMs: input.nowMs,
    catalogVersion: input.catalogVersion,
    items,
    total: {
      amountMinor: subtotalsByCurrency(input.cart)[CHECKOUT_CURRENCY]!,
      currency: CHECKOUT_CURRENCY,
    },
    destination: input.destination,
    payment: input.payment,
    acknowledgedSimulation: true,
    simulation: newSimulationRecord(input.scenario, input.nowMs),
  };
  return { ok: true, status: "created", order };
}
